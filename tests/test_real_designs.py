"""The exporter on two SoCs it did not grow up with (D24): Croc, written by hand, and Didactic SoC, made in Kactus2.

Each one is built into an IP-XACT library, generated by the `xactflow rtl-gen` command, and checked against what
its own project has: Croc's hand-written croc_soc and croc_domain, elaborated in slang with Croc's testbench, and
Didactic's RTL and the tops Kactus2 generated for it. The scripts in tests/real_designs do the work, and each also
runs on its own and prints the details (see tests/real_designs/README.md).

These tests need clones of the two projects, named by environment variables, and are skipped without them:

    CROC_DIR=../croc DIDACTIC_DIR=../Didactic-SoC pytest tests/test_real_designs.py

The numbers below are those of the commits CI checks out (.github/workflows/build.yml). Another commit may
legitimately change them; a difference between the generated and the hand-written module may not.
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

import pytest
from xactflow import cli

HERE = Path(__file__).resolve().parent / "real_designs"
sys.path[:0] = [str(HERE / "croc"), str(HERE / "didactic")]

CROC = os.environ.get("CROC_DIR")
DIDACTIC = os.environ.get("DIDACTIC_DIR")
needs_croc = pytest.mark.skipif(not CROC, reason="CROC_DIR does not name a clone of pulp-platform/croc")
needs_didactic = pytest.mark.skipif(not DIDACTIC, reason="DIDACTIC_DIR does not name a clone of Edu4Chip/Didactic-SoC")

# What compare_connections.py counts in each module, at Croc 71abd392.
CROC_COUNTS = {
    "croc_soc": {"bits": 373, "instances": 3, "parameters": 4, "differences": 0},
    "croc_domain": {"bits": 3396, "instances": 19, "parameters": 106, "differences": 0},
}

# Didactic d67a723c: what differs from Kactus2's tops, and what slang says about the generated modules.
# SysCtrl_SS's output pmod_sel is 8 bits in Didactic's RTL, NUM_GPIO (6) in its IP-XACT, and 16 in the top
# Kactus2 generated from an older IP-XACT, which leaves the 8 bits above the RTL's open. prepare_library.py gives
# the port the RTL's width (WIDTHS_FROM_THE_RTL).
DIDACTIC_ENDPOINTS = {
    "Didactic": 1016, "SysCtrl_SS_wrapper_1": 1088, "SysCtrl_SS_1": 1871, "analog_wrapper": 268,
    "dtu_wrapper": 170, "imt_wrapper": 166, "kth_wrapper": 166, "tum_wrapper": 166,
}  # fmt: skip
DIDACTIC_DIFFERENCES = {"SysCtrl_SS_1": {f"top:pmod_sel[{bit}]": ("(absent)", "OPEN") for bit in range(8, 16)}}
# io_cell_frame_sysctrl.sv has an inout clk_out its component does not have, so nothing connects it.
DIDACTIC_SLANG = ["UnconnectedInOutPort: SysCtrl_SS_wrapper_1.sv:197: ) i_io_cell_frame (   ['clk_out']"]


def generate(design: Path, library: Path, out: Path, *arguments: str) -> Path:
    """Run the exporter as a user would, through the xactflow command."""
    assert cli.main(["rtl-gen", str(design), "--lib", str(library), "--output", str(out), *arguments]) == 0
    return out


@pytest.fixture(scope="module")
def croc(tmp_path_factory):
    import build_library

    work = tmp_path_factory.mktemp("croc")
    library = work / "library"
    build_library.build(Path(CROC), library)
    rtl = generate(
        library / "pulp-platform.org_design_croc_soc_d_1.0.xml", library, work / "rtl",
        "--option", "common=clk_i,rst_ni,testmode_i,ref_clk_i", "--option", "filelist=croc_soc.f",
    )  # fmt: skip
    return Path(CROC), rtl, work


@pytest.fixture(scope="module")
def didactic(tmp_path_factory):
    import prepare_library

    work = tmp_path_factory.mktemp("didactic")
    library = work / "library"
    prepare_library.prepare(Path(DIDACTIC), library)
    top = library / "tuni.fi" / "soc" / "Didactic" / "1.2"
    rtl = generate(top / "Didactic.design.1.2.xml", library, work / "rtl", "--config", str(top / "Didactic.designcfg.1.2.xml"))
    return Path(DIDACTIC), library, rtl


@needs_croc
def test_croc_generates_its_two_modules_and_a_file_list(croc):
    _, rtl, _ = croc
    assert sorted(p.name for p in rtl.iterdir()) == ["croc_domain_1.sv", "croc_soc.f", "croc_soc.sv"]


@needs_croc
def test_croc_testbench_elaborates_with_the_generated_modules_as_with_the_hand_written_ones(croc):
    import check_slang

    found = check_slang.check(*croc)
    assert found["in_generated_files"] == []
    assert found["new_in_croc_files"] == []
    assert check_slang.summary(found["generated"]) == check_slang.summary(found["reference"])


@needs_croc
def test_croc_every_bit_and_parameter_is_the_same_as_in_the_hand_written_modules(croc):
    import compare_connections

    assert compare_connections.compare_all(*croc) == CROC_COUNTS


@needs_didactic
def test_didactic_connects_every_bit_as_kactus2_did(didactic):
    import compare_kactus2

    report = compare_kactus2.compare(*didactic)
    assert {module: result["endpoints"] for module, result in report.items()} == DIDACTIC_ENDPOINTS
    assert {module: r["differences"] for module, r in report.items() if r["differences"]} == DIDACTIC_DIFFERENCES
    assert {module: r["problems"] for module, r in report.items() if any(r["problems"].values())} == {}


@needs_didactic
def test_didactic_generated_modules_fit_its_rtl(didactic):
    import check_with_rtl

    source, _, rtl = didactic
    found, _ = check_with_rtl.check(source, rtl)
    assert found == DIDACTIC_SLANG
