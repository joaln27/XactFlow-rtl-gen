"""Write a module's netlist as SystemVerilog.

Every net is declared, each assign of a connection becomes an `assign` from the driving net to the receiving
one, and each instance is written with its parameters and ports. That one shape covers part selects, inverted
port maps, tie-offs and struct sub-ports without special cases, and every line of the output says who drives
whom. Nothing is decided here: what connects to what, and what is refused, was settled when the netlist was
built (wiring.py).
"""

from __future__ import annotations

import re
from typing import List, Set

from .expressions import single_token, sv_number
from .keywords import SYSTEMVERILOG_KEYWORDS
from .netlist import IN, INOUT, OUT, Assign, Block, Constant, Instance, Module, Reference, Select, SignalType, one_line

GENERATED_MARKER = "// Generated by xactflow-rtl-gen"


def header(source: object) -> str:
    """The first line of every generated file: what wrote it, and what from."""
    from . import __version__

    return f"{GENERATED_MARKER} {__version__} from {source}. Do not edit."


def render(module: Module) -> str:
    """The module as SystemVerilog text."""
    labels: Set[str] = set()  # generate blocks share the module's one scope with nets, ports and instances
    lines = [header(module.source)]
    lines.extend(f"// {remark}" for remark in module.remarks)
    lines.append("")
    lines.extend(_module_header(module))
    lines.extend(_parameter_checks(module, labels))
    if module.notes:
        lines.extend(f"    // {note}" for note in module.notes)
        lines.append("")
    if module.nets:
        width = max(len(_type(net.type)) for net in module.nets)
        lines.extend(f"    {_type(net.type):<{width}} {net.name};" for net in module.nets)
        lines.append("")
    for block in module.blocks:
        lines.extend(f"    // {comment}" for comment in block.comment)
        lines.extend(_assigns(module, block, labels))
        lines.append("")
    for instance in module.instances:
        lines.extend(_instance(instance))
        lines.append("")
    lines.append("endmodule")
    return "\n".join(lines) + "\n"


def _type(signal_type: SignalType) -> str:
    """`logic [15:0]`, `pkg::req_t [3:0]`: a type's name, then its packed dimensions."""
    dimensions = "".join(f"[{left}:{right}]" for left, right in signal_type.dimensions)
    return signal_type.name + (" " if dimensions else "") + dimensions


def _select(select: Select) -> str:
    """`[7:4]`, `[3]`, `.addr`, `[3].addr`, or nothing for the whole signal."""
    if select.bounds is not None:
        return f"[{select.bounds[0]}:{select.bounds[1]}]{select.path}"
    return (f"[{select.element}]" if select.element is not None else "") + select.path


def _side(reference: Reference) -> str:
    return f"{reference.net}{_select(reference.select)}"


def _constant(constant: Constant, cast: bool) -> str:
    if constant.width is not None:
        return f"{constant.width}'h{constant.value & ((1 << constant.width) - 1):x}"
    if constant.value == -1 and not cast:
        return "'1"  # all ones at whatever width the sink has, where -1 is a signed number cut to fit
    return sv_number(constant.value)


def _sv_string(text: str) -> str:
    """A string literal for a message: $error reads it as a format, so a percent sign is doubled."""
    return '"' + one_line(text).replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%") + '"'


def _compiler_check(condition: str, label: str, message: str, at_run_time: bool = True) -> List[str]:
    """What the generated module has the compiler check, where only the compiler can. `$error` stops a tool as
    it elaborates the module. One that skips such a line, or reports it and goes on, stops when its simulation
    starts, on the `$fatal` (D40). `at_run_time` is False for a condition on `$bits`: with Icarus 12 the
    `$fatal` of such a block stopped simulations that had nothing wrong."""
    text = _sv_string(message)
    stop = [f"        initial $fatal(1, {text});"] if at_run_time else []
    return [f"    if ({condition}) begin : {label}", f"        $error({text});", *stop, "    end"]


def _check_label(module: Module, wanted: str, labels: Set[str]) -> str:
    """A name for a generate block that the module's one scope does not have yet, nor SystemVerilog."""
    taken = {
        *(net.name for net in module.nets),
        *(port.name for port in module.ports),
        *(instance.name for instance in module.instances),
        *(parameter.name for parameter in module.parameters),
    }
    name, tries = wanted, 1
    while name in labels or name in taken or name in SYSTEMVERILOG_KEYWORDS:
        name, tries = f"{wanted}{tries}", tries + 1
    labels.add(name)
    return name


def _module_header(module: Module) -> List[str]:
    lines = [f"module {module.name} ("]
    if module.parameters:
        rows = [f"    parameter {p.type_name + ' ' if p.type_name else ''}{p.name} = {p.value}" for p in module.parameters]
        lines = [f"module {module.name} #(", ",\n".join(rows), ") ("]
    if not module.ports:
        return [*lines[:-1], f"{lines[-1]});", ""]
    width = max(len(_type(port.type)) for port in module.ports)
    keywords = {IN: "input ", OUT: "output", INOUT: "inout "}
    rows = [f"    {keywords[port.direction]} {_type(port.type):<{width}} {port.name}" for port in module.ports]
    return [*lines, ",\n".join(rows), ");", ""]


def _parameter_checks(module: Module, labels: Set[str]) -> List[str]:
    """Everything in the module is worked out for one value of each parameter, so the compiler refuses
    an instance that gives another (D36). A parameter is declared with no type, so it takes the type of what
    it is given, and the check compares that with the value as it is written here, nothing converted in
    between. Only a typedef named with its package is kept, and the check then casts the value to it as the
    declaration does (D41). `!==` tells x and z apart too, where `!=` would not know and so let any value
    through, but it takes no real number and no string."""
    if not module.parameters:
        return []
    lines = ["    // Every width and value below is worked out for these values of the parameters. For others,", "    // generate the module again."]
    for parameter in module.parameters:
        value = parameter.value if single_token(parameter.value) else f"({parameter.value})"
        if parameter.type_name:  # what the declaration makes of the value, on this side too
            value = f"{parameter.type_name}'({parameter.value})"
        message = f"{module.name} is generated for {parameter.name} = {parameter.value}, and was given another value"
        label = _check_label(module, parameter.name + "_as_generated", labels)
        differs = "!==" if parameter.integral else "!="
        lines.extend(_compiler_check(f"{parameter.name} {differs} {value}", label, message))
    lines.append("")
    return lines


def _assigns(module: Module, block: Block, labels: Set[str]) -> List[str]:
    def source_of(assign: Assign) -> str:
        if isinstance(assign.source, Constant):
            source = _constant(assign.source, bool(assign.cast))
        else:
            source = ("~" if assign.source.invert else "") + _side(assign.source)
        return f"{assign.cast}'({source})" if assign.cast else source

    width = max((len(_side(assign.sink)) for assign in block.assigns), default=0)
    rows = []
    for assign in block.assigns:
        comment = f"  // {assign.note}" if assign.note else ""
        rows.append(f"    assign {_side(assign.sink):<{width}} = {source_of(assign)};{comment}")
    for assign in block.assigns:
        if assign.check is not None:
            # Only the compiler knows how wide a typedef is, so it checks the constant isn't cut short.
            sink = _side(assign.sink)
            label = _check_label(module, re.sub(r"\W+", "_", sink).strip("_") + "_fits", labels)
            rows.extend(_compiler_check(f"$bits({sink}) < {assign.check.bits}", label, assign.check.message, at_run_time=False))
    return rows


def _instance(instance: Instance) -> List[str]:
    lines = [f"    // {comment}" for comment in instance.comments]
    if instance.parameters:
        lines.append(f"    {instance.module} #(")
        lines.append(",\n".join(f"        .{name}({value})" for name, value in instance.parameters))
        lines.append(f"    ) {instance.name} (")
    else:
        lines.append(f"    {instance.module} {instance.name} (")

    connections = instance.connections
    width = max((len(connection.port) for connection in connections), default=0)
    remaining = len(connections)
    for group in instance.groups:
        if group.heading is not None:
            lines.append(f"        // {group.heading}")
        for connection in group.connections:
            remaining -= 1
            note = f"  // {connection.note}" if connection.note else ""
            lines.append(f"        .{connection.port:<{width}} ({connection.net or ''})" + ("," if remaining else "") + note)
    lines.append("    );")
    return lines
